export function help(nsfw) {
  const l = ['Команды Specter', '',
    'Действия: напиши /команда @ник или ответь на сообщение командой',
    Object.entries(acts).map(([k, v]) => `${v.e} /${k}`).join('  '), '',
    'Разное',
    '🎲 /кубик   🪙 /монетка   🎱 /шар вопрос   🤖 /спек вопрос',
    'Чтобы позвать ИИ, упомяни @spec или ответь на его сообщение']
  if (nsfw) l.push('', '18+ (только в этой группе)', Object.entries(hot).map(([k, v]) => `${v.e} /${k}`).join('  '))
  return l.join('\n')
}

export function parse(body) {
  const m = /^\/([\p{L}\d_]+)(?:@\w+)?\s*([\s\S]*)$/u.exec(body.trim())
  if (!m) return null
  return { cmd: m[1].toLowerCase().replace(/ё/g, 'е'), rest: m[2].trim() }
}

const norm = o => Object.fromEntries(Object.entries(o).map(([k, v]) => [k.replace(/ё/g, 'е'), v]))
const A = norm(acts), H = norm(hot)

export function findAct(cmd, nsfw) {
  if (A[cmd]) return A[cmd]
  if (H[cmd]) return nsfw ? H[cmd] : 'locked'
  return null
}

export function fun(cmd, rest) {
  if (cmd === 'кубик' || cmd === 'dice') return { e: '🎲', t: '{a} бросает кубик: ' + (1 + Math.floor(Math.random() * 6)) }
  if (cmd === 'монетка' || cmd === 'coin') return { e: '🪙', t: '{a} подбрасывает монетку: ' + (Math.random() < .5 ? 'орёл' : 'решка') }
  if (cmd === 'шар' || cmd === '8ball') return { e: '🎱', t: `{a} спрашивает шар${rest ? ` «${rest.slice(0, 200)}»` : ''}: ${ball[Math.floor(Math.random() * ball.length)]}` }
  return null
}

export function render(a, from, to) {
  return to || !a.all ? a.t.replace('{a}', from).replace('{b}', to) : a.all.replace('{a}', from)
}
